export function formatPackLabel(id: string): string {
  return id
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

export function pickRandomQuestion(
  packs: Record<string, string[]>,
  enabled: string[],
  used: string[] = []
): { question: string; packId: string } | null {
  const pool: { question: string; packId: string }[] = [];
  for (const id of enabled) {
    for (const question of packs[id] || []) {
      if (!used.includes(question)) pool.push({ question, packId: id });
    }
  }
  if (!pool.length) {
    for (const id of enabled) {
      for (const question of packs[id] || []) {
        pool.push({ question, packId: id });
      }
    }
  }
  if (!pool.length) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}
